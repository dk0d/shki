use std::io::Write;
use std::path::{Path, PathBuf};

use heck::ToSnakeCase;

use crate::Result;
use crate::commands::codegen::CodegenConfig;
use crate::commands::codegen::writer::CodeWriter;

use super::{GeneratedRust, RustStruct};

